/**
 * Patrika Magazine Playbook — 10 premium content "pockets".
 *
 * Each magazine's Idea-generation and Content-generation prompts are built from
 * a single universal template (Appendix A of the playbook) parameterised by the
 * magazine's metadata below. The built defaults are registered as editable
 * Writing Directives (controls "magazineIdea" / "magazineContent") in
 * lib/ai/directives.ts, so the desk can tune any magazine's prompt from
 * /directives. The magazine generator (/magazines) reads the effective prompt.
 */

export type Magazine = {
  key: string;
  // Which side-section the desk belongs to. Omitted = "patrika" (Patrika+
  // Special Content). "olloi" desks render under the separate Olloi Content
  // section (e.g. the Saath cancer-support content).
  group?: "patrika" | "olloi";
  nameEn: string;
  nameHi: string;
  tagline: string;       // positioning (Hindi)
  reader: string;        // target audience (Hindi)
  age: string;
  cadence: string;       // publishing cadence (Hindi) — display only
  subVerticals: string[]; // 5 micro-niches (Hindi)
  structure: string;     // magazine-specific middle of the article structure (Hindi)
  compliance: string;    // magazine-specific compliance note (Hindi)
  // Desk-level Google-News search terms. When set (news-oriented desks), idea
  // generation reads real, fresh articles from these instead of an open
  // web-search digest — the same read-real-articles path the politics
  // "current" filter uses, but for the whole desk (no filter needed).
  newsQueries?: string[];
  // Optional desk-specific angle filters. When present, the desk shows a filter
  // picker; the chosen filter's `brief` steers both idea generation and the
  // article. `brief` is a Hindi instruction usable in either prompt.
  //
  // `newsQueries`: when a filter needs the LATEST real news (e.g. current
  // political issues), these Google-News search terms fetch fresh, dated
  // headlines that seed idea generation — a live feed, fresher than open search.
  filters?: Array<{ key: string; label: string; brief: string; newsQueries?: string[] }>;
  // Starter questions (Olloi / health desks): one-tap seeds for the
  // question → multiple-ideas fan-out.
  questionBank?: string[];
};

